// Writes src/styles/icons.css with only the Iconoir icons the site uses.
// The full Iconoir stylesheet is 2.8 MB; the subset is a few kilobytes.
//
// It finds icons by scanning the source for "iconoir-<name>", so using a new
// icon needs nothing more than writing its class name.
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const VENDOR = join(ROOT, 'vendor', 'iconoir.css')
const OUT = join(ROOT, 'src', 'styles', 'icons.css')

async function sourceFiles(dir: string): Promise<string[]> {
  const out: string[] = []
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name)
    if (e.isDirectory()) out.push(...(await sourceFiles(p)))
    else if (/\.(ts|tsx)$/.test(e.name)) out.push(p)
  }
  return out
}

if (!existsSync(VENDOR)) {
  if (existsSync(OUT)) {
    console.log('icons: vendor/iconoir.css not present, keeping the existing icons.css')
    process.exit(0)
  }
  throw new Error('vendor/iconoir.css is missing and there is no icons.css to fall back on')
}

const used = new Set<string>()
for (const f of await sourceFiles(join(ROOT, 'src'))) {
  for (const m of (await readFile(f, 'utf8')).matchAll(/iconoir-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) used.add(m[1])
}

const vendor = await readFile(VENDOR, 'utf8')
const rules: string[] = []
const missing: string[] = []
for (const name of [...used].sort()) {
  const m = new RegExp(`\\.iconoir-${name}::before\\{mask-image:(url\\('[^']*'\\))`).exec(vendor)
  if (m) rules.push(`.iconoir-${name}::before{--i:${m[1]}}`)
  else missing.push(name)
}
if (missing.length) throw new Error(`icons: not in Iconoir: ${missing.join(', ')}`)

const css = `/* Generated by scripts/build-icons.ts. Do not edit.
 * Icons: Iconoir (https://iconoir.com), MIT License, Copyright (c) Luca Burgio. */
[class^='iconoir-'],[class*=' iconoir-']{display:inline-flex;align-items:center;justify-content:center;line-height:1;vertical-align:-.125em}
[class^='iconoir-']::before,[class*=' iconoir-']::before{content:'';display:block;flex:none;width:1em;height:1em;background:currentColor;-webkit-mask:var(--i) center/cover no-repeat;mask:var(--i) center/cover no-repeat}
${rules.join('\n')}
`
await writeFile(OUT, css)
console.log(`icons: ${rules.length} icons, ${(css.length / 1024).toFixed(1)} KB`)
